"""Toolpath -> KUKA KRL program (.src) for KR C4 / KSS 8.x.

Cartesian points are written inline relative to BASE_DATA[base_number], so
no .dat file is needed. PTP moves are written as joint angles (from our IK)
so the arm configuration on the robot matches the simulation. External axes:
E1 (gantry) is set by the PTP moves (a move's axes["E1"], else the cell's position); the turntable axes are written on every
point.

Turntable modes (cell.turntable.coupled):
  coupled     - the controller moves BASE_DATA with the faceplate: points are
                relative to the part and $VEL.CP is the speed over the part.
  not coupled - points are in the fixed base (faceplate at tilt = rotation = 0);
                $VEL.CP and $VEL_EXTAX are set per move so robot and table
                both take the planned time (speed over the part).

Part base (`part_base`, a KRL base picked on the part): Cartesian points are
written relative to that frame and the program selects
BASE_DATA[part_base_number], taught on the real part. With the turntable not
coupled it is taught with the table axes at 0. PTP joint values are unchanged.

Spray on/off uses WAIT SEC to stop the advance run, so outputs switch exactly
when the robot reaches the point rather than early. A move's `dwell_s` is a
WAIT SEC after it (e.g. at a powder purge point).
"""

import numpy as np

from coldspray.cell import base_in_robot, base_world, base_worlds, gantry_position, table_axis_names
from coldspray.kinematics.robot import Robot
from coldspray.models import CellConfig, ProcessConfig
from coldspray.toolpath.model import Toolpath, move_length
from coldspray.transforms import xyzabc


class KRLError(Exception):
    pass


def _axis(q, external: dict[str, float] | None = None) -> str:
    items = [f"A{i + 1} {v:.3f}" for i, v in enumerate(q)]
    items += [f"{k} {v:.3f}" for k, v in (external or {}).items()]
    return "{" + ", ".join(items) + "}"


def _pos(pose, external: dict[str, float] | None = None) -> str:
    items = [f"{k} {x:.3f}" for k, x in zip("XYZABC", xyzabc(pose))]
    items += [f"{k} {v:.3f}" for k, v in (external or {}).items()]
    return "{" + ", ".join(items) + "}"


def to_krl(path: Toolpath, robot: Robot, cell: CellConfig, proc: ProcessConfig,
           part_base: np.ndarray | None = None) -> str:
    """`part_base`: faceplate BASE <- KRL base on the part (Part.placement @ Part.krl_base),
    or None to write relative to the faceplate BASE."""
    name = path.name[:24]
    gun = f"$OUT[{cell.gun_output}]"
    home = cell.home_deg
    tt = cell.turntable
    table_names = table_axis_names(cell)
    coupled = bool(tt and tt.coupled)
    fixed_base_inv = np.linalg.inv(base_world(cell, {k: 0.0 for k in table_names}))
    e1_axis = cell.gantry.axis if cell.gantry else None
    e1_default = gantry_position(cell) if cell.gantry else None

    defaults = {tt.tilt.axis: tt.tilt.position_deg, tt.rotation.axis: tt.rotation.position_deg} if tt else {}
    axes_per_move = [defaults | a for a in path.axis_values()]
    table = [{k: a[k] for k in table_names} for a in axes_per_move]
    # E1 per move: set on a move's axes (solver), else the cell's position
    e1s = [({e1_axis: gantry_position(cell, a.get(e1_axis))} if e1_axis else {}) for a in axes_per_move]

    to_part = np.eye(4) if part_base is None else np.linalg.inv(part_base)
    base_number = cell.base_number if part_base is None else cell.part_base_number

    in_fixed_base = fixed_base_inv @ base_worlds(cell, table)           # per move: BASE -> fixed base

    def cartesian(i, pose=None):
        """TCP pose of move i (or `pose` at move i's table position) as written in the program."""
        pose = path.moves[i].pose if pose is None else pose
        return to_part @ (pose if coupled else in_fixed_base[i] @ pose)

    if part_base is None:
        base_note = [f";BASE_DATA[{base_number}] / TOOL_DATA[{cell.tool_number}] must match the cell config"]
    else:
        zero = {k: 0.0 for k in table_names}
        seen = "the faceplate" if coupled else "WORLD, table axes at 0"
        base_note = [
            f";BASE_DATA[{base_number}] taught on the part (KRL base picked in the Part step);"
            f" TOOL_DATA[{cell.tool_number}] must match the cell config",
            f";  expected in {seen}: " + " ".join(
                f"{k} {x:.2f}" for k, x in zip("XYZABC", xyzabc(part_base if coupled
                                                               else base_world(cell, zero) @ part_base)))]

    lines = [
        "&ACCESS RVP",
        "&REL 1",
        f"DEF {name}( )",
        f";Generated by coldspray: {len(path.moves)} moves",
        *base_note,
        f";Turntable {'coupled to the base' if coupled else 'not coupled: positions in the fixed base'}"
        if tt else ";No turntable",
        ";FOLD INI",
        "  BAS(#INITMOV, 0)",
        ";ENDFOLD",
        f"BAS(#TOOL, {cell.tool_number})",
        f"BAS(#BASE, {base_number})",
        f"BAS(#VEL_PTP, {cell.ptp_velocity_pct})",
        f"$APO.CDIS = {proc.approx_distance_mm:.1f}",
        f"{gun} = FALSE",
        *(["$CIRC_TYPE = #PATH", "$ORI_TYPE = #VAR"] if any(m.kind == "CIRC" for m in path.moves) else []),
        "",
        f"PTP {_axis(home)}  ;home",
    ]

    seed = np.asarray(home, dtype=float)
    vel = {}
    gun_on = False
    moves = path.moves

    def set_vel(var, value, comment=""):
        text = f"{value:.4f}" if var == "$VEL.CP" else f"{value:.1f}"
        if vel.get(var) != text:
            vel[var] = text
            lines.append(f"{var} = {text}" + (f"  ;{comment}" if comment else ""))

    def dwell(m):
        """Wait at the point; the move there is never blended, so the robot stops on it."""
        if m.dwell_s > 0:
            lines.append(f"WAIT SEC {m.dwell_s:g}  ;dwell")

    for i, m in enumerate(moves):
        if m.gun_on != gun_on:
            lines += ["WAIT SEC 0", f"{gun} = {'TRUE' if m.gun_on else 'FALSE'}"]
            if m.gun_on:
                lines.append(f"WAIT SEC {proc.spray_settle_s:.1f}  ;spray settle")
            gun_on = m.gun_on

        # A gantry move goes as PTP (joints + E1), never as a LIN that would leave E1 behind
        if m.kind == "PTP" or (i > 0 and e1s[i] != e1s[i - 1]):
            sols = robot.ik(base_in_robot(cell, table[i], e1s[i].get(e1_axis)) @ m.pose, seed)
            if not sols:
                raise KRLError(f"move {i}: PTP target is unreachable")
            seed = sols[0]
            lines.append(f"PTP {_axis(seed, e1s[i] | table[i])}")
            dwell(m)
            continue

        if i == 0 or coupled or not tt:
            set_vel("$VEL.CP", m.speed / 1000, f"{m.speed:g} mm/s")
        else:
            # Plan the move time from the speed over the part, then make the
            # robot's (fixed-base) motion and each table axis take that time.
            over_part = move_length(moves[i - 1].pose, m)
            turns = {k: abs(table[i][k] - table[i - 1][k]) for k in table_names}
            limits = {tt.tilt.axis: tt.tilt.max_speed_deg_s, tt.rotation.axis: tt.rotation.max_speed_deg_s}
            t = over_part / m.speed
            for k, deg in turns.items():
                if deg > 1e-9 and limits[k]:
                    t = max(t, deg / limits[k])
            if t <= 0:
                set_vel("$VEL.CP", m.speed / 1000, f"{m.speed:g} mm/s")
            else:
                robot_mm = (over_part if m.kind == "CIRC" and not any(turns.values())  # rigid: same arc
                            else np.linalg.norm(cartesian(i)[:3, 3] - cartesian(i - 1)[:3, 3]))
                set_vel("$VEL.CP", max(robot_mm / t / 1000, 0.0001))
                for k, deg in turns.items():
                    if deg > 1e-9 and limits[k]:
                        set_vel(f"$VEL_EXTAX[{k[1:]}]", min(100.0, 100.0 * deg / t / limits[k]))
        nxt = moves[i + 1] if i + 1 < len(moves) else None
        blend = nxt is not None and nxt.gun_on == m.gun_on and nxt.kind in ("LIN", "CIRC") and not m.dwell_s
        if m.kind == "CIRC":
            lines.append(f"CIRC {_pos(cartesian(i, m.aux), table[i])}, {_pos(cartesian(i), table[i])}"
                         + (" C_DIS" if blend else ""))
        else:
            lines.append(f"LIN {_pos(cartesian(i), table[i])}" + (" C_DIS" if blend else ""))
        dwell(m)

    if gun_on:
        lines += ["WAIT SEC 0", f"{gun} = FALSE"]
    lines += ["", f"PTP {_axis(home)}  ;home", "END", ""]
    return "\n".join(lines)
